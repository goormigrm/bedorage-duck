export type MapId = 'studio' | 'yard'

export interface MapTheme {
  /** 바닥 기본/보조 색 */
  floor: number
  floorAlt: number
  floorLine: number
  /** 벽 옆면/윗면 색 */
  wall: number
  wallTop: number
  /** 낮은 상자 색 */
  crate: number
  /** 배경(맵 밖) */
  outside: number
  /** 조명 색 (3D) */
  sunColor: number
  ambientColor: number
  /** 안개 색 (3D) */
  fog: number
}

/** 안쪽 구조물 생성 밀도 (40x30 기준 개수, 맵이 넓어지면 비례해 늘어난다) */
export interface MapGen {
  /** 벽 덩어리 (막대·ㄱ자·블록) */
  blocks: number
  /** 상자 군집 */
  crates: number
  /** 흩어진 모래주머니 줄 (중앙 진지는 항상 별도로 생긴다) */
  sandbags: number
  /** 벽 덩어리 최대 길이 */
  maxLen: number
}

export interface MapDef {
  id: MapId
  name: string
  desc: string
  /** 크기·테두리 전용 (안쪽 글자는 무시된다) */
  rows: string[]
  gen: MapGen
  theme: MapTheme
}

