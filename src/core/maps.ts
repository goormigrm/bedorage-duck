// 문자 그리드: # 벽, . 바닥, S 스폰 후보, o 낮은 상자(벽과 동일 충돌, 렌더에서 낮게)

export type MapId = 'studio' | 'yard'

export interface MapTheme {
  /** 바닥 기본/보조 색 */
  floor: number
  floorAlt: number
  floorLine: number
  /** 벽 옆면/윗면 색 */
  wall: number
  wallTop: number
  /** 낮은 상자 색 */
  crate: number
  /** 배경(맵 밖) */
  outside: number
  /** 조명 색 (3D) */
  sunColor: number
  ambientColor: number
  /** 안개 색 (3D) */
  fog: number
}

export interface MapDef {
  id: MapId
  name: string
  desc: string
  rows: string[]
  theme: MapTheme
}

